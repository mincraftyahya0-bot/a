import turtle
turtle.speed(10)
turtle.pensize(4)

turtle.up()
turtle.goto(-50, 150)
turtle.down()
turtle.goto(-50, -150)

turtle.up()
turtle.goto(50, 150)
turtle.down()
turtle.goto(50, -150)

turtle.up()
turtle.goto(-150, 50)
turtle.down()
turtle.goto(150, 50)

turtle.up()
turtle.goto(-150, -50)
turtle.down()
turtle.goto(150, -50)

turtle.hideturtle()
turtle.done()
